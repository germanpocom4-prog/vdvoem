// Точное время (в минутах) для конкретных идей, где оно указано в тексте
export const IDEA_TIMERS = {
  // 18+
  a2: 5,   // Смотри в глаза 5 минут
  a3: 10,  // Прикосновения без рук 10 минут
  a6: 3,   // Медленный поцелуй 3 минуты
  a7: 5,   // Описать фантазию 5 минут
  a21: 5,  // Поцелуй в шею 5 минут

  // Помириться
  mk4: 1,  // Обняться на 60 секунд

  // Весёлые
  f2: 2,   // Нарисуй меня с закрытыми глазами 2 минуты
  f4: 5,   // Испорченный телефон жестами 5 минут
  f5: 20,  // Фотоохота 20 минут
  f11: 1,  // Мимика-баттл 60 секунд
  f18: 5,  // Угадай предмет на ощупь

  // Романтика
  r13: 3,  // Танец на кухне 3 минуты
};

// Возвращает количество минут для таймера или null, если таймер не нужен
export function getIdeaTimer(idea) {
  if (IDEA_TIMERS[idea.id]) return IDEA_TIMERS[idea.id];
  return null;
}